-- Schema inicial. Os CHECKs de enum espelham os enums do domínio (RequestStatus, Category, StepLevel, StepStatus,
-- Role, ApproverLevel): ao alterar um enum, crie uma nova migration ajustando o CHECK correspondente.

CREATE TABLE cost_center (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(30)  NOT NULL,
    name       varchar(120) NOT NULL,
    created_at timestamptz  NOT NULL,
    CONSTRAINT uq_cost_center_code UNIQUE (code)
);

CREATE TABLE app_user (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(120) NOT NULL,
    email          varchar(254) NOT NULL,
    password_hash  varchar(100) NOT NULL,
    role           varchar(20)  NOT NULL,
    approver_level varchar(10),
    cost_center_id bigint REFERENCES cost_center (id),
    created_at     timestamptz  NOT NULL,
    updated_at     timestamptz  NOT NULL,
    CONSTRAINT ck_app_user_role CHECK (role IN ('SOLICITANTE', 'APROVADOR', 'ADMIN')),
    CONSTRAINT ck_app_user_approver_level CHECK (approver_level IN ('NIVEL_1', 'NIVEL_2')),
    -- Igualdade booleana = os dois sentidos: APROVADOR exige nível; os demais papéis exigem nível NULL.
    CONSTRAINT ck_app_user_level_only_for_approver CHECK ((role = 'APROVADOR') = (approver_level IS NOT NULL)),
    -- ADMIN pode ser global; os demais papéis dependem do centro de custo para visibilidade e elegibilidade.
    CONSTRAINT ck_app_user_cost_center_required CHECK (role = 'ADMIN' OR cost_center_id IS NOT NULL)
);

CREATE UNIQUE INDEX uq_app_user_email ON app_user (lower(email));
CREATE INDEX idx_app_user_cost_center ON app_user (cost_center_id);

-- month guarda o 1º dia do mês de competência (YearMonth no domínio).
CREATE TABLE budget (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_center_id bigint        NOT NULL REFERENCES cost_center (id),
    month          date          NOT NULL,
    amount         numeric(19, 2) NOT NULL,
    consumed       numeric(19, 2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_budget_cost_center_month UNIQUE (cost_center_id, month),
    CONSTRAINT ck_budget_month_first_day CHECK (extract(day FROM month) = 1),
    -- Última defesa: o UPDATE condicional já impede o estouro; isto garante que nenhum caminho o contorne.
    CONSTRAINT ck_budget_consumed_within_amount CHECK (consumed >= 0 AND consumed <= amount)
);

-- lock_version é o @Version (controle otimista); current_version é o número da versão de negócio (v1, v2...).
CREATE TABLE purchase_request (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        bigint      NOT NULL REFERENCES app_user (id),
    cost_center_id  bigint      NOT NULL REFERENCES cost_center (id),
    status          varchar(20) NOT NULL,
    current_version integer     NOT NULL,
    lock_version    bigint      NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    CONSTRAINT ck_purchase_request_status CHECK (
        status IN ('DRAFT', 'PENDING_APPROVAL', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_purchase_request_current_version CHECK (current_version >= 1)
);

-- Índices para visibilidade (dono / centro de custo) e filtros, com created_at para a ordenação padrão.
CREATE INDEX idx_purchase_request_owner ON purchase_request (owner_id, created_at);
CREATE INDEX idx_purchase_request_cost_center ON purchase_request (cost_center_id, created_at);
CREATE INDEX idx_purchase_request_status ON purchase_request (status, created_at);
CREATE INDEX idx_purchase_request_created_at ON purchase_request (created_at);

CREATE TABLE request_version (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       bigint         NOT NULL REFERENCES purchase_request (id),
    version_number   integer        NOT NULL,
    title            varchar(200)   NOT NULL,
    description      varchar(2000)  NOT NULL,
    category         varchar(20)    NOT NULL,
    needed_by        date,
    total            numeric(19, 2) NOT NULL,
    submitted_at     timestamptz,
    competence_month date,
    created_at       timestamptz    NOT NULL,
    CONSTRAINT uq_request_version_number UNIQUE (request_id, version_number),
    CONSTRAINT ck_request_version_number CHECK (version_number >= 1),
    CONSTRAINT ck_request_version_category CHECK (
        category IN ('EQUIPMENT', 'SERVICES', 'SUPPLIES', 'TRAVEL', 'SOFTWARE', 'OTHER')),
    CONSTRAINT ck_request_version_total CHECK (total >= 0),
    -- A competência é calculada no submit: as duas colunas nascem juntas.
    CONSTRAINT ck_request_version_submission CHECK ((submitted_at IS NULL) = (competence_month IS NULL)),
    CONSTRAINT ck_request_version_competence_first_day CHECK (extract(day FROM competence_month) = 1)
);

CREATE INDEX idx_request_version_category ON request_version (category);

CREATE TABLE request_item (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id  bigint         NOT NULL REFERENCES request_version (id) ON DELETE CASCADE,
    line_number integer        NOT NULL,
    description varchar(500)   NOT NULL,
    quantity    integer        NOT NULL,
    unit_price  numeric(19, 2) NOT NULL,
    -- Adiável: o Hibernate insere os itens novos antes de apagar os antigos ao trocar a coleção; a checagem fica
    -- para o commit, quando a renumeração já terminou.
    CONSTRAINT uq_request_item_line_number UNIQUE (version_id, line_number) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_request_item_line_number CHECK (line_number >= 0),
    CONSTRAINT ck_request_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_request_item_unit_price CHECK (unit_price > 0)
);

CREATE TABLE approval_step (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id bigint      NOT NULL REFERENCES request_version (id),
    step_order integer     NOT NULL,
    level      varchar(10) NOT NULL,
    status     varchar(20) NOT NULL,
    decided_by bigint REFERENCES app_user (id),
    decided_at timestamptz,
    comment    varchar(2000),
    CONSTRAINT uq_approval_step_order UNIQUE (version_id, step_order),
    -- Cada nível aparece no máximo uma vez por versão (a etapa ADMIN nunca é duplicada).
    CONSTRAINT uq_approval_step_level UNIQUE (version_id, level),
    CONSTRAINT ck_approval_step_order CHECK (step_order >= 1),
    CONSTRAINT ck_approval_step_level CHECK (level IN ('NIVEL_1', 'NIVEL_2', 'ADMIN')),
    CONSTRAINT ck_approval_step_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CHANGES_REQUESTED')),
    -- Mesmo invariante do record ApprovalStep: pendente não tem decisor; decidida tem decisor e data.
    CONSTRAINT ck_approval_step_decision CHECK (
        (status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND decided_by IS NOT NULL AND decided_at IS NOT NULL))
);

-- Segregação de funções como última defesa: a mesma pessoa não aprova duas etapas da mesma versão.
CREATE UNIQUE INDEX uq_approval_step_approver ON approval_step (version_id, decided_by) WHERE status = 'APPROVED';
CREATE INDEX idx_approval_step_pending ON approval_step (level) WHERE status = 'PENDING';

-- http_request_id é o X-Request-Id da requisição que gerou o evento (rastreabilidade com os logs).
CREATE TABLE request_event (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      bigint       NOT NULL REFERENCES purchase_request (id),
    version_number  integer      NOT NULL,
    actor_id        bigint       NOT NULL REFERENCES app_user (id),
    actor_role      varchar(20)  NOT NULL,
    action          varchar(30)  NOT NULL,
    from_status     varchar(20),
    to_status       varchar(20)  NOT NULL,
    step_level      varchar(10),
    comment         varchar(2000),
    occurred_at     timestamptz  NOT NULL,
    http_request_id varchar(128),
    CONSTRAINT ck_request_event_actor_role CHECK (actor_role IN ('SOLICITANTE', 'APROVADOR', 'ADMIN')),
    CONSTRAINT ck_request_event_from_status CHECK (
        from_status IN ('DRAFT', 'PENDING_APPROVAL', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_request_event_to_status CHECK (
        to_status IN ('DRAFT', 'PENDING_APPROVAL', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_request_event_step_level CHECK (step_level IN ('NIVEL_1', 'NIVEL_2', 'ADMIN'))
);

CREATE INDEX idx_request_event_request ON request_event (request_id, occurred_at, id);

-- Histórico append-only garantido no banco. TRUNCATE (limpeza dos testes) não dispara gatilhos de linha.
CREATE FUNCTION forbid_request_event_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'request_event é append-only: % não é permitido', TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER trg_request_event_append_only
    BEFORE UPDATE OR DELETE ON request_event
    FOR EACH ROW EXECUTE FUNCTION forbid_request_event_change();

-- Resposta salva na mesma transação da criação; a UNIQUE resolve a corrida entre requisições com a mesma chave.
CREATE TABLE idempotency_key (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint      NOT NULL REFERENCES app_user (id),
    key             varchar(255) NOT NULL,
    request_hash    char(64)    NOT NULL,
    response_status integer     NOT NULL,
    response_body   jsonb       NOT NULL,
    created_at      timestamptz NOT NULL,
    CONSTRAINT uq_idempotency_key_user_key UNIQUE (user_id, key),
    CONSTRAINT ck_idempotency_key_response_status CHECK (response_status BETWEEN 100 AND 599)
);

CREATE INDEX idx_idempotency_key_created_at ON idempotency_key (created_at);
